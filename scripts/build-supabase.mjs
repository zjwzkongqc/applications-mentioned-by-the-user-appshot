import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const functionDirectory = path.join(root, 'supabase/functions/tennis-api');
const destination = path.join(root, 'dist/supabase/tennis-api.ts');

// Reuse the same asset injection as the standalone server. The generated
// worker remains the unchanged shared handler with ordinary Web APIs only.
await import('./build-node.mjs');
await fs.mkdir(functionDirectory, { recursive: true });
await fs.copyFile(path.join(root, 'dist/node/worker.mjs'), path.join(functionDirectory, 'worker.mjs'));

// Resolve the entry point's complete dependency graph, including owner-import
// modules added later. A real bundler preserves lexical scopes and exports.
const bundled = await build({
  absWorkingDir: root,
  entryPoints: [path.join(functionDirectory, 'index.ts')],
  outfile: destination,
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  external: ['npm:postgres@3.4.7'],
  write: false,
  metafile: true,
  sourcemap: false,
  legalComments: 'none',
  // esbuild emits JavaScript and erases source types. The .ts extension is for
  // the Dashboard entry point, not a second typecheck of generated JS helpers.
  banner: { js: '// @ts-nocheck\n// Generated by scripts/build-supabase.mjs. Deploy this complete file; edit its source modules.' }
});
const externalImports = Object.values(bundled.metafile.outputs).flatMap(output => output.imports).filter(imported => imported.external);
if (externalImports.some(imported => imported.path !== 'npm:postgres@3.4.7')) throw new Error('The Edge bundle contains an unexpected runtime dependency.');
if (bundled.outputFiles.length !== 1) throw new Error('The Dashboard deployment requires one complete Edge module.');
await fs.mkdir(path.dirname(destination), { recursive: true });
await fs.writeFile(destination, bundled.outputFiles[0].contents);
console.log('Built Supabase function sources and the single-file Dashboard module.');
